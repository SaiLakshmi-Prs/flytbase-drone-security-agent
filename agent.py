@dataclass
class SecurityAlert:
    """Represents an actionable alert generated by the agent."""

    alert_id: Optional[int]
    timestamp: datetime.datetime
    frame_id: int
    severity: str  # "INFO", "WARNING", "ALERT", "CRITICAL"
    rule_name: str
    message: str
    location_name: str
    details: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Convert alert to dictionary representation."""
        return {
            "alert_id": self.alert_id,
            "timestamp": self.timestamp.isoformat(),
            "frame_id": self.frame_id,
            "severity": self.severity,
            "rule_name": self.rule_name,
            "message": self.message,
            "location_name": self.location_name,
            "details": self.details,
        }

    def format_canonical(self) -> str:
        """Format alert matching assignment specification: 'Person loitering at main gate, 00:01.'"""
        time_str = self.timestamp.strftime("%H:%M")
        return f"Alert: {self.message}"


class EntityStateTracker:
    """Maintains cross-frame state, visit frequencies, and loitering durations for entities."""

    def __init__(self) -> None:
        # entity_id -> list of observation timestamps and locations
        self.observations: Dict[str, List[Tuple[datetime.datetime, str, int]]] = {}
        # entity_id -> consecutive frame count
        self.consecutive_frames: Dict[str, int] = {}
        # last frame_id seen
        self.last_frame_seen: Dict[str, int] = {}

    def update(
        self, entity: DetectedEntity, frame_id: int, timestamp: datetime.datetime, location: str
    ) -> Dict[str, Any]:
        """Update tracker state with a new sighting of an entity.

        Returns:
            Dict with 'total_visits', 'consecutive_count', 'is_repeat_entry'.
        """
        eid = entity.entity_id
        if eid not in self.observations:
            self.observations[eid] = []
            self.consecutive_frames[eid] = 0

        # Check continuity
        prev_frame = self.last_frame_seen.get(eid, -99)
        if frame_id == prev_frame + 1:
            self.consecutive_frames[eid] += 1
        else:
            self.consecutive_frames[eid] = 1

        self.last_frame_seen[eid] = frame_id
        self.observations[eid].append((timestamp, location, frame_id))

        # Check if this counts as a separate visit (gap of > 30 minutes between sightings)
        visits = self._count_distinct_visits(eid)

        return {
            "total_observations": len(self.observations[eid]),
            "distinct_visits": visits,
            "consecutive_count": self.consecutive_frames[eid],
            "is_repeat_visit": visits > 1,
        }

    def _count_distinct_visits(self, entity_id: str, gap_minutes: int = 30) -> int:
        """Count distinct visits separated by a temporal inactivity gap."""
        obs = self.observations.get(entity_id, [])
        if not obs:
            return 0
        visits = 1
        for i in range(1, len(obs)):
            delta = obs[i][0] - obs[i - 1][0]
            if delta.total_seconds() > (gap_minutes * 60):
                visits += 1
        return visits

    def get_visit_count(self, entity_id: str) -> int:
        """Get the number of distinct visits for an entity."""
        return self._count_distinct_visits(entity_id)

    def get_loitering_duration_sec(self, entity_id: str) -> float:
        """Estimate current loitering span in seconds."""
        obs = self.observations.get(entity_id, [])
        if len(obs) < 2:
            return 0.0
        return (obs[-1][0] - obs[0][0]).total_seconds()


class DroneSecurityAnalystAgent:
    """Autonomous Security Agent responsible for real-time threat detection,

    sliding-window behavioral analysis, session summarization, and natural language Q&A.
    """

    def __init__(self, indexer: FrameIndexer) -> None:
        """Initialize agent with persistent frame indexer and state tracker."""
        self.indexer = indexer
        self.state_tracker = EntityStateTracker()
        self.recent_alerts: List[SecurityAlert] = []
        self.sliding_window_frames: List[PerceptionResult] = []
        self.max_window_size: int = 10

    def process_frame(
        self, frame: VideoFrame, perception: PerceptionResult
    ) -> List[SecurityAlert]:
        """Analyze a frame's perception result, evaluate rules, update state, and return alerts.

        Args:
            frame: Synchronized video frame with telemetry.
            perception: Structured entity extraction result.

        Returns:
            List of triggered SecurityAlert objects.
        """
        # 1. Update sliding window
        self.sliding_window_frames.append(perception)
        if len(self.sliding_window_frames) > self.max_window_size:
            self.sliding_window_frames.pop(0)

        # 2. Persist frame into SQLite indexer
        self.indexer.index_frame(frame, perception)

        # 3. Evaluate safety & security rules
        new_alerts: List[SecurityAlert] = []
        timestamp = frame.timestamp
        time_str = timestamp.strftime("%H:%M")
        location = frame.telemetry.location_name

        for entity in perception.entities:
            state = self.state_tracker.update(
                entity, frame.frame_id, timestamp, location
            )

            # Rule 1: Midnight / After-Hours Loitering
            # e.g., 'Person loitering at main gate, 00:01.'
            if entity.category == "person" and not entity.attributes.get("authorized", False):
                is_after_hours = timestamp.hour >= 23 or timestamp.hour <= 4
                is_loitering = entity.attributes.get("loitering", False)

                if is_after_hours and is_loitering:
                    # Check for immediate breach attempt vs general loitering
                    if entity.attributes.get("breach_attempt", False):
                        severity = "CRITICAL"
                        rule_name = "UNAUTHORIZED_PERIMETER_BREACH"
                        msg = f"Unauthorized person attempting perimeter breach at {location.lower()}, {time_str}"
                    else:
                        severity = "ALERT"
                        rule_name = "AFTER_HOURS_LOITERING"
                        msg = f"Person loitering at {location.lower()}, {time_str}"

                    alert = SecurityAlert(
                        alert_id=None,
                        timestamp=timestamp,
                        frame_id=frame.frame_id,
                        severity=severity,
                        rule_name=rule_name,
                        message=msg,
                        location_name=location,
                        details={
                            "entity_id": entity.entity_id,
                            "attire": entity.attributes.get("attire"),
                            "consecutive_frames": state["consecutive_count"],
                        },
                    )
                    new_alerts.append(alert)

            # Rule 2: Repeat Vehicle Visit Detection
            # "a blue Ford F150 entered twice today"
            if entity.category == "vehicle" and state["is_repeat_visit"]:
                # Check if we already alerted for this specific frame visit
                if state["consecutive_count"] == 1:
                    visit_num = state["distinct_visits"]
                    alert = SecurityAlert(
                        alert_id=None,
                        timestamp=timestamp,
                        frame_id=frame.frame_id,
                        severity="WARNING",
                        rule_name="REPEAT_VEHICLE_ACTIVITY",
                        message=f"{entity.label} re-entered property (visit #{visit_num} today) at {location.lower()}, {time_str}",
                        location_name=location,
                        details={
                            "entity_id": entity.entity_id,
                            "visits_count": visit_num,
                        },
                    )
                    new_alerts.append(alert)

            # Rule 3: Critical Drone Telemetry Hazards
            if entity.category == "telemetry_hazard":
                alert = SecurityAlert(
                    alert_id=None,
                    timestamp=timestamp,
                    frame_id=frame.frame_id,
                    severity="CRITICAL",
                    rule_name="DRONE_LOW_BATTERY_RTH",
                    message=f"Critical drone battery alert ({entity.attributes.get('battery_percent', 0):.1f}%) over {location.lower()}, {time_str}",
                    location_name=location,
                    details=entity.attributes,
                )
                new_alerts.append(alert)

        # 4. Record alerts in persistent database
        for alert in new_alerts:
            aid = self.indexer.record_alert(
                frame_id=alert.frame_id,
                timestamp=alert.timestamp,
                severity=alert.severity,
                rule_name=alert.rule_name,
                message=alert.message,
                location_name=alert.location_name,
                details=alert.details,
            )
            alert.alert_id = aid
            self.recent_alerts.append(alert)

        return new_alerts

    # -------------------------------------------------------------------------
    # Bonus Feature 1: Video Session Summarization
    # -------------------------------------------------------------------------

    def generate_session_summary(self) -> Dict[str, Any]:
        """Synthesize a high-level 1-sentence summary of the entire monitoring session

        along with an executive metrics brief.
        """
        stats = self.indexer.get_session_stats()
        alerts = self.indexer.query_alerts()
        trucks = self.indexer.query_truck_events()

        # Count repeat visits
        f150_visits = self.state_tracker.get_visit_count("vehicle:ford_f150_blue")
        loiter_alerts = [a for a in alerts if "loitering" in a["message"].lower()]
        critical_alerts = [a for a in alerts if a["severity"] == "CRITICAL"]

        loc_str = ", ".join(stats["monitored_locations"][:4])
        if len(stats["monitored_locations"]) > 4:
            loc_str += f", and {len(stats['monitored_locations']) - 4} other zones"

        # 1-Sentence Executive Summary Formulation
        f150_note = f"a blue Ford F150 entered twice" if f150_visits >= 2 else "routine vehicle access"
        loiter_note = (
            f"identified suspicious midnight loitering at Main Gate"
            if loiter_alerts
            else "no perimeter breaches"
        )
        battery_note = (
            "and safely managed a low-battery RTH procedure"
            if any("battery" in a["message"].lower() for a in alerts)
            else "with nominal drone telemetry"
        )

        one_sentence_summary = (
            f"Over {stats['total_frames']} monitored patrol frames across {len(stats['monitored_locations'])} property zones, "
            f"the Drone Security Analyst Agent logged {stats['unique_entities']} distinct entities (notably {f150_note}), "
            f"{loiter_note}, {battery_note}."
        )

        return {
            "one_sentence_summary": one_sentence_summary,
            "total_frames_processed": stats["total_frames"],
            "unique_entities_detected": stats["unique_entities"],
            "total_security_alerts": stats["total_alerts"],
            "critical_events": len(critical_alerts),
            "zones_monitored": stats["monitored_locations"],
            "time_window": f"{stats['start_time']} to {stats['end_time']}",
        }

    # -------------------------------------------------------------------------
    # Bonus Feature 2: Interactive Natural Language Q&A Engine
    # -------------------------------------------------------------------------

    def answer_question(self, question: str) -> str:
        """Answer follow-up natural language questions over indexed property events on demand.

        Handles queries such as:
        - 'What objects were in the video?'
        - 'Show all truck events'
        - 'How many times did the blue Ford F150 enter?'
        - 'Were there any alerts at midnight?'
        - 'What happened at the main gate?'
        """
        q_lower = question.lower().strip()

        # Query 1: What objects were in the video?
        if "what objects" in q_lower or "what entities" in q_lower or "list objects" in q_lower:
            cursor = self.indexer.conn.cursor()
            cursor.execute(
                """
                SELECT label, category, COUNT(*) as detections
                FROM entities
                GROUP BY label
                ORDER BY detections DESC;
                """
            )
            rows = cursor.fetchall()
            if not rows:
                return "No objects were detected during the surveillance session."
            items = [f"- {r['label']} ({r['category']}, detected {r['detections']} time(s))" for r in rows]
            return (
                f"The following {len(rows)} distinct objects/entities were identified across the video frames:\n"
                + "\n".join(items)
            )

        # Query 2: Truck events / 'show all truck events'
        if "truck" in q_lower:
            trucks = self.indexer.query_truck_events()
            if not trucks:
                return "No truck events were indexed during this monitoring session."
            lines = [
                f"- Frame #{t['frame_id']} [{t['timestamp'][11:16]} at {t['location_name']}]: {t['primary_log_message']}"
                for t in trucks
            ]
            return (
                f"Found {len(trucks)} indexed truck event(s):\n"
                + "\n".join(lines)
            )

        # Query 3: Blue Ford F150 visit count / 'entered twice today'
        if ("ford" in q_lower or "f150" in q_lower or "blue truck" in q_lower) and (
            "how many" in q_lower or "twice" in q_lower or "visit" in q_lower or "enter" in q_lower
        ):
            count = self.state_tracker.get_visit_count("vehicle:ford_f150_blue")
            trucks = self.indexer.query_truck_events()
            timestamps = [t["timestamp"][11:16] for t in trucks]
            times_str = " and ".join(timestamps) if timestamps else "earlier"
            return (
                f"A blue Ford F150 entered {count} times today. Sighted at garage at {times_str}."
            )

        # Query 4: Midnight / After-hours alerts
        if "midnight" in q_lower or "00:" in q_lower or "after hours" in q_lower or "night" in q_lower:
            alerts = self.indexer.query_alerts()
            midnight_alerts = [
                a for a in alerts
                if datetime.datetime.fromisoformat(a["timestamp"]).hour in [23, 0, 1, 2, 3]
            ]
            if not midnight_alerts:
                return "No security alerts were triggered around midnight."
            lines = [
                f"- [{a['severity']}] {a['timestamp'][11:16]} at {a['location_name']}: {a['message']}"
                for a in midnight_alerts
            ]
            return (
                f"Detected {len(midnight_alerts)} alert(s) during after-hours/midnight operations:\n"
                + "\n".join(lines)
            )

        # Query 5: Location specific queries (e.g., 'main gate', 'garage')
        for loc in ["main gate", "garage", "loading bay", "fuel depot", "north gate"]:
            if loc in q_lower:
                results = self.indexer.query_by_location(loc)
                if not results:
                    return f"No events recorded at {loc.title()}."
                lines = [
                    f"- Frame #{r['frame_id']} [{r['timestamp'][11:16]}]: {r['primary_log_message']}"
                    for r in results
                ]
                return f"Events recorded at {loc.title()} ({len(results)} occurrences):\n" + "\n".join(lines)

        # Query 6: General Alerts summary
        if "alert" in q_lower or "security" in q_lower or "threat" in q_lower:
            alerts = self.indexer.query_alerts()
            if not alerts:
                return "Zero security alerts were triggered during this session."
            lines = [
                f"- [{a['severity']}] {a['timestamp'][11:16]} at {a['location_name']}: {a['message']}"
                for a in alerts
            ]
            return f"Summary of {len(alerts)} recorded security alert(s):\n" + "\n".join(lines)

        # Fallback: Full-Text Search across indexed video database
        fts_matches = self.indexer.search_full_text(question.replace("?", "").strip())
        if fts_matches:
            lines = [
                f"- Frame #{m['frame_id']} [{m['timestamp'][11:16]} at {m['location_name']}]: {m['primary_log_message']}"
                for m in fts_matches[:5]
            ]
            return (
                f"I found {len(fts_matches)} relevant indexed frame(s) matching your query:\n"
                + "\n".join(lines)
            )

        return (
            f"Query received: '{question}'. No specific database matches found. "
            "You can ask about detected objects, truck events, midnight alerts, or specific locations."
        )
